//! **bookmarks-core** — ядро приложения Bookmarks.
//!
//! Крейт намеренно не знает ничего о Tauri, окнах и вебе: здесь живут
//! доменные модели, хранилище (SQLite + FTS5), поисковый движок, история
//! версий, крипто-сейф, механизм синхронизации и экспорт/импорт. Обёртка
//! `src-tauri` лишь пробрасывает эти операции в IPC-команды, поэтому ядро
//! целиком покрыто тестами и запускается без GUI.
//!
//! Слои:
//! - [`domain`] — модели и их инварианты (нормализация текста, лимиты);
//! - [`db`] — схема, миграции, чтение и запись, [`db::Store`] как точка входа;
//! - [`search`] — парсер запроса и ранжированная выдача с подсветкой;
//! - [`versions`] — снапшоты заметок, откат, очистка по политике;
//! - [`crypto`] — контейнер `BKENC1` (PBKDF2 + AES-256-GCM) для сейфа;
//! - [`sync`] — трёхстороннее слияние и транспорт [`sync::Remote`];
//! - [`export`] — Markdown / JSON / HTML экспорт и импорт обратно.

pub mod crypto;
pub mod db;
pub mod domain;
pub mod error;
pub mod export;
pub mod ids;
pub mod search;
pub mod sync;
pub mod time;
pub mod versions;

pub use db::Store;
pub use error::{Error, Result};

