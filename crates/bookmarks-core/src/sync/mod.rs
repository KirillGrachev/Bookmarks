//! Синхронизация между устройствами.
//!
//! Модель: каждое устройство хранит в общем хранилище свой манифест
//! (`devices/<device_id>.json`) с отпечатками всех заметок — идентификатор,
//! хеш содержимого, метка изменения и признак удаления. Тел заметок в манифесте
//! нет, поэтому сравнение состояний дешёвое даже для большой библиотеки.
//!
//! Синхронизация проходит в три шага:
//! 1. читаем свой предыдущий манифест (база) и манифесты остальных устройств;
//! 2. для каждой заметки сравниваем три состояния (база / локальное / удалённое)
//!    и получаем действие: без изменений, выгрузить, скачать, удалить или
//!    конфликт;
//! 3. применяем действия и записываем новый манифест.
//!
//! Конфликт — это случай, когда заметку изменили на двух устройствах после
//! общей базы. По умолчанию побеждает самая свежая правка, а проигравшая версия
//! не теряется: она сохраняется в историю версий и, по настройке, дублируется
//! заметкой «… (конфликт)».
//!
//! Транспорт абстрагирован трейтом [`Remote`]: папка (включая сетевую), WebDAV
//! и тестовое хранилище в памяти реализуют один интерфейс.

