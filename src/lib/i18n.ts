export type DictKey = keyof (typeof dict)['ru'];

/** Проверка, что английский словарь покрывает все ключи русского. */
const missingInEn = (Object.keys(dict.ru) as DictKey[]).filter((key) => !(key in dict.en));
if (missingInEn.length > 0) {
  // Не бросаем исключение: интерфейс должен работать, но в dev-режиме это видно сразу.
  console.warn(`[i18n] missing keys in "en": ${missingInEn.join(', ')}`);
}

/** Перевод по ключу с подстановкой `{count}` и подобных. */
export function translate(lang: Lang, key: DictKey, vars?: Record<string, string | number>): string {
  const template =
    (dict[lang] as Record<string, string>)[key] ?? (dict.ru as Record<string, string>)[key] ?? key;
  if (!vars) {
    return template;
  }
  return template.replace(/\{(\w+)\}/g, (match, name: string) => (name in vars ? String(vars[name]) : match));
}

/**
 * Функция перевода, привязанная к языку.
 *
 * Ключ объявлен как `string`, а не как `DictKey`: часть ключей строится
 * динамически (`sort.${value}`, `settings.theme.${theme}`,
 * `versions.origin.${origin}`), и на таких местах строгий литеральный тип
 * заставляет писать `as never`, который хуже отсутствующей проверки — он
 * отключает её целиком. Опечатки в статических ключах ловят тесты словаря.
 */
export type Translator = (key: string, vars?: Record<string, string | number>) => string;

export function createTranslator(lang: Lang): Translator {
  return (key, vars) => translate(lang, key as DictKey, vars);
}

/** Определяет язык интерфейса по настройке и локали системы. */
export function resolveLanguage(preferred: Lang | null, systemLocales: readonly string[]): Lang {
  if (preferred) {
    return preferred;
  }
  const primary = systemLocales[0]?.toLowerCase() ?? '';
  return primary.startsWith('ru') ? 'ru' : 'en';
}
